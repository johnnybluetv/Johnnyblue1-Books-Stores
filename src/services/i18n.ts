/**
 * Retrieves a translated string with optional variable replacement
 * Example: getTranslation('en', 'showing_titles', { count: 12 }) -> "Showing 12 titles"
 */
export const getTranslation = (
  lang: LanguageCode, 
  key: string, 
  params?: Record<string, string | number>
): string => {
  const dictionary = TRANSLATIONS[lang] || TRANSLATIONS.en;
  let text = dictionary[key] || TRANSLATIONS.en[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
};

/**
 * Format currency according to the selected global locale
 */
export const formatCurrency = (amount: number, lang: LanguageCode): string => {
  switch (lang) {
    case 'ja':
      return `¥${Math.round(amount * 150).toLocaleString()}`;
    case 'zh':
      return `¥${(amount * 7.2).toFixed(2)}`;
    case 'ar':
      return `${(amount * 3.75).toFixed(2)} ر.س`;
    case 'tw':
      return `GH₵ ${(amount * 15.5).toFixed(2)}`;
    case 'fr':
    case 'de':
    case 'es':
    case 'pt':
      return `€${(amount * 0.92).toFixed(2)}`;
    case 'en':
    default:
      return `$${amount.toFixed(2)}`;
  }
};

/**
 * Helper to get the text direction ('ltr' or 'rtl') for a language code
 */
export const getLanguageDirection = (lang: LanguageCode): 'ltr' | 'rtl' => {
  const opt = SUPPORTED_LANGUAGES.find((l) => l.code === lang);
  return opt?.dir || 'ltr';
};
